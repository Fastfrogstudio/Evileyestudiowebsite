export const GLYPH_WIDTH = 5;
export const GLYPH_HEIGHT = 7;

/** Width in pixels of `text` at the given scale, including inter-glyph gaps. */
export function measureText(text, scale = 1, tracking = 1) {
	if (!text.length) return 0;
	return text.length * (GLYPH_WIDTH + tracking) * scale - tracking * scale;
}

/**
 * Draw `text` onto a Canvas with its top-left at (x, y).
 * Unknown characters fall back to '?' so a label can never silently vanish.
 */
export function drawText(canvas, text, x, y, colour, scale = 1, tracking = 1) {
	let cursor = x;
	for (const char of String(text).toUpperCase()) {
		const glyph = GLYPHS[char] ?? GLYPHS['?'];
		for (let row = 0; row < GLYPH_HEIGHT; row += 1) {
			for (let col = 0; col < GLYPH_WIDTH; col += 1) {
				if (glyph[row][col] !== '1') continue;
				canvas.fillRect(cursor + col * scale, y + row * scale, scale, scale, colour);
			}
		}
		cursor += (GLYPH_WIDTH + tracking) * scale;
	}
}

/** Draw `text` horizontally centred within [x, x + width). */
export function drawTextCentred(canvas, text, x, y, width, colour, scale = 1, tracking = 1) {
	const w = measureText(text, scale, tracking);
	drawText(canvas, text, x + Math.round((width - w) / 2), y, colour, scale, tracking);
}
