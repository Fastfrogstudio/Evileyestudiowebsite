export const BOARD_MECHANIC_KEYS = Object.keys(BOARD_MECHANICS);

/** The spec keys under `game:` that switch a board mechanic on. */
export const BOARD_MECHANIC_SPEC_KEYS = BOARD_MECHANIC_KEYS.map((k) => BOARD_MECHANICS[k].specKey);

/** Look one up by the spec key that enables it. */
export function boardMechanicFor(specKey) {
	return Object.values(BOARD_MECHANICS).find((m) => m.specKey === specKey) ?? null;
}
