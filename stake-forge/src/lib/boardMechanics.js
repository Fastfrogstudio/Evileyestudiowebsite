/**
 * Board mechanics — the ones that are a post-processor on the board.
 *
 * ── Why these are a registry and not one function each ──────────────────────
 * A large share of the interesting mechanics in slots are the same shape: after
 * the board is drawn (or refilled by a cascade), walk it and rewrite some cells.
 * Random wilds, mystery symbols, symbol upgrades, conversions, spawners,
 * guaranteed wilds on a cascade — all of them.
 *
 * Writing a bespoke scaffolder function per mechanic means writing the same
 * splice-and-import plumbing every time, and getting it subtly different every
 * time. So the plumbing lives once in mathScaffold.applyBoardMechanics and each
 * mechanic is DATA: the Python method it needs, where to call it, which
 * evaluators it makes sense on, and what it costs the art team.
 *
 * ── The two rules every entry here obeys ────────────────────────────────────
 * 1. It declares a `boardLifetime`, like every board-writing recipe, so the
 *    cascade knows whether to restore it after a refill. This is the same
 *    abstraction that fixed expanding-wilds-on-a-cascade, applied at the point
 *    a new mechanic is added rather than after it breaks.
 *
 * 2. It states which `winTypes` it is meaningful on, and the spec loader
 *    refuses it elsewhere. A wild-substitution mechanic on scatter-pays would
 *    generate, run, and do nothing — the worst outcome, because it looks like
 *    it works.
 *
 * ── Provenance ──────────────────────────────────────────────────────────────
 * Where a mechanic is associated with a particular game, the entry says so.
 * These are plain-language RULES built from math-sdk primitives. No studio's
 * assets, bundles or source were fetched or inspected.
 */

/**
 * @typedef {object} BoardMechanic
 * @property {string}   id
 * @property {string}   name
 * @property {string}   specKey       the key under `game:` that switches it on
 * @property {string[]} winTypes      evaluators it is meaningful on
 * @property {string}   boardLifetime how long its writes survive
 * @property {string}   seenIn        the game that popularised it, or ''
 * @property {string[]} imports       python modules the emitted method needs
 * @property {(cfg: object) => string} method   the python method source
 * @property {string}   call          the call to splice in
 * @property {'after-draw'|'after-cascade'|'both'} site
 * @property {string[]} [conditions]  distribution condition keys it reads
 */

/** Indent a block of python to a method body. */
